// Bakes the built single-file dashboard into a TS module so `tsc` ships it with the CLI.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = fileURLToPath(new URL("../", import.meta.url));
const repoRoot = path.resolve(packageRoot, "../..");

const builtHtml = readFileSync(path.join(packageRoot, "dist", "index.html"), "utf8");

const PLACEHOLDER = "__SHRINKER_STATS_JSON__";
if (!builtHtml.includes(PLACEHOLDER)) {
  throw new Error(`Built dashboard is missing the ${PLACEHOLDER} placeholder`);
}

const target = path.join(repoRoot, "src", "metrics", "dashboard-template.generated.ts");
const contents = `// Generated by packages/dashboard-ui/scripts/emit-template.mjs. Do not edit.
export const DASHBOARD_STATS_PLACEHOLDER = ${JSON.stringify(PLACEHOLDER)};

export const DASHBOARD_TEMPLATE_HTML = ${JSON.stringify(builtHtml)};
`;

writeFileSync(target, contents, "utf8");
if (!process.env.SHRINKER_BUILD_QUIET) {
  process.stdout.write(`Wrote ${path.relative(repoRoot, target)} (${builtHtml.length} bytes of HTML)\n`);
}
